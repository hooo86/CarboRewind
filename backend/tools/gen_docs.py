"""Generate the reference documents derived from the code.

* ``docs/schema.sql``  — SQL of all Alembic migrations (offline mode)
* ``docs/openapi.json`` — OpenAPI specification of the API
* ``docs/rbac.md``     — permission matrix (between the GENERATED markers)

Usage (from ``backend/``): ``python tools/gen_docs.py [--check]``. ``--check`` exits 1 if a
committed file is out of date (used by the test suite).
"""

from __future__ import annotations

import io
import json
import sys
from pathlib import Path

from alembic import command
from alembic.config import Config

BACKEND = Path(__file__).resolve().parents[1]
DOCS = BACKEND.parent / "docs"
BEGIN, END = "<!-- BEGIN GENERATED MATRIX -->", "<!-- END GENERATED MATRIX -->"


def render_schema() -> str:
    buffer = io.StringIO()
    cfg = Config(str(BACKEND / "alembic.ini"), output_buffer=buffer)
    cfg.attributes["url"] = "postgresql+psycopg://offline@localhost/offline"
    command.upgrade(cfg, "head", sql=True)
    lines = [line.rstrip() for line in buffer.getvalue().splitlines()]
    header = (
        "-- CarboRewind control-plane schema (PostgreSQL 16).\n"
        "-- GENERATED by `python backend/tools/gen_docs.py` from the Alembic migrations.\n"
        "-- Do not edit by hand.\n\n"
    )
    return header + "\n".join(lines).strip() + "\n"


def render_openapi() -> str:
    from carborewind_api.config import Settings
    from carborewind_api.main import create_app

    spec = create_app(Settings(environment="test")).openapi()
    return json.dumps(spec, indent=2, ensure_ascii=False, sort_keys=True) + "\n"


def render_rbac(current: str) -> str:
    from carborewind_api.authz import GLOBAL_ONLY, MATRIX, Permission
    from carborewind_api.db.models import Role

    roles = [Role.SUPER_ADMIN, Role.DOMAIN_ADMIN, Role.RESTORE_OPERATOR, Role.VIEWER]
    rows = ["| Permission | " + " | ".join(f"`{r.value}`" for r in roles) + " |"]
    rows.append("|---|" + "---|" * len(roles))
    for perm in Permission:
        suffix = " (global uniquement)" if perm in GLOBAL_ONLY else ""
        cells = ["✅" if perm in MATRIX[r] else "—" for r in roles]
        rows.append(f"| `{perm.value}`{suffix} | " + " | ".join(cells) + " |")
    table = "\n".join(rows)
    start, end = current.index(BEGIN) + len(BEGIN), current.index(END)
    return current[:start] + "\n" + table + "\n" + current[end:]


def targets() -> dict[Path, str]:
    rbac = DOCS / "rbac.md"
    return {
        DOCS / "schema.sql": render_schema(),
        DOCS / "openapi.json": render_openapi(),
        rbac: render_rbac(rbac.read_text()),
    }


def main(argv: list[str]) -> int:
    stale = []
    for path, content in targets().items():
        if "--check" in argv:
            if not path.is_file() or path.read_text() != content:
                stale.append(path)
        else:
            path.write_text(content)
    for path in stale:
        print(f"{path} is out of date: run python tools/gen_docs.py", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.path.insert(0, str(BACKEND / "src"))
    sys.exit(main(sys.argv[1:]))
