#!/usr/bin/env bash
# CarboRewind server installer (single host, Docker Compose).
#
#   sudo ./deploy/install-server.sh --server-name carborewind.example.org \
#        [--tls-cert fullchain.pem --tls-key privkey.pem] [--install-dir /opt/carborewind]
#
# Idempotent: re-running it upgrades the stack (rebuild + migrations) and never overwrites
# existing secrets, TLS material or the agents' CA.
set -euo pipefail

INSTALL_DIR=/opt/carborewind
SERVER_NAME=""
TLS_CERT=""
TLS_KEY=""

die() { echo "error: $*" >&2; exit 1; }
say() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }

while [ $# -gt 0 ]; do
    case "$1" in
        --server-name) SERVER_NAME="${2:-}"; shift 2 ;;
        --tls-cert) TLS_CERT="${2:-}"; shift 2 ;;
        --tls-key) TLS_KEY="${2:-}"; shift 2 ;;
        --install-dir) INSTALL_DIR="${2:-}"; shift 2 ;;
        -h|--help) sed -n '2,9p' "$0"; exit 0 ;;
        *) die "unknown option $1" ;;
    esac
done

[ "$(id -u)" = "0" ] || die "run as root (sudo)"
[[ "$SERVER_NAME" =~ ^[A-Za-z0-9]([A-Za-z0-9.-]{0,251}[A-Za-z0-9])?$ ]] \
    || die "--server-name must be a DNS name, e.g. carborewind.example.org"
if [ -n "$TLS_CERT$TLS_KEY" ]; then
    [ -r "$TLS_CERT" ] && [ -r "$TLS_KEY" ] || die "--tls-cert and --tls-key must both be readable files"
fi
command -v docker >/dev/null || die "Docker is required (https://docs.docker.com/engine/install/)"
docker compose version >/dev/null 2>&1 || die "Docker Compose v2 plugin is required"
command -v openssl >/dev/null || die "openssl is required"

SRC="$(cd "$(dirname "$0")/.." && pwd)"
umask 077

say "installing files into $INSTALL_DIR"
mkdir -p "$INSTALL_DIR"
if [ "$SRC" != "$(cd "$INSTALL_DIR" && pwd)" ]; then
    for part in backend frontend deploy docs LICENSE README.md CHANGELOG.md; do
        [ -e "$SRC/$part" ] || continue
        rm -rf "${INSTALL_DIR:?}/$part.new"
        cp -a "$SRC/$part" "$INSTALL_DIR/$part.new"
        # Keep the generated secrets and TLS files of a previous installation.
        if [ "$part" = deploy ] && [ -d "$INSTALL_DIR/deploy" ]; then
            for keep in .env tls; do
                [ -e "$INSTALL_DIR/deploy/$keep" ] && cp -a "$INSTALL_DIR/deploy/$keep" "$INSTALL_DIR/deploy.new/"
            done
        fi
        rm -rf "${INSTALL_DIR:?}/$part"
        mv "$INSTALL_DIR/$part.new" "$INSTALL_DIR/$part"
    done
fi
cd "$INSTALL_DIR/deploy"
COMPOSE=(docker compose -f docker-compose.prod.yml)

if [ ! -f .env ]; then
    say "generating secrets (.env, mode 0600)"
    rand() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "$1"; }
    cat > .env <<ENV
# Generated by install-server.sh — keep this file secret and backed up.
SERVER_NAME=$SERVER_NAME
POSTGRES_DB=carborewind
POSTGRES_USER=carborewind
POSTGRES_PASSWORD=$(rand 40)
CARBOREWIND_AGENT_PROXY_SECRET=$(rand 48)
CARBOREWIND_LOG_LEVEL=INFO
ENV
else
    say "keeping existing .env"
    sed -i "s/^SERVER_NAME=.*/SERVER_NAME=$SERVER_NAME/" .env
fi
# Encrypts secrets stored in the database (SMTP password…). Added to older installs too;
# losing it means re-entering those secrets, never losing backups.
if ! grep -q '^CARBOREWIND_SECRET_KEY=' .env; then
    say "generating CARBOREWIND_SECRET_KEY"
    echo "CARBOREWIND_SECRET_KEY=$(openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c 48)" >> .env
fi
# Bearer token for Prometheus to scrape https://<server>/metrics.
if ! grep -q '^CARBOREWIND_METRICS_TOKEN=' .env; then
    say "generating CARBOREWIND_METRICS_TOKEN (Prometheus)"
    echo "CARBOREWIND_METRICS_TOKEN=$(openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c 40)" >> .env
fi
chmod 600 .env

mkdir -p tls
if [ -n "$TLS_CERT" ]; then
    say "installing the provided TLS certificate"
    install -m 0644 "$TLS_CERT" tls/server.crt
    install -m 0600 "$TLS_KEY" tls/server.key
elif [ ! -f tls/server.crt ]; then
    say "no certificate given: generating a self-signed one for $SERVER_NAME (825 days)"
    openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 -nodes -days 825 \
        -subj "/CN=$SERVER_NAME" -addext "subjectAltName=DNS:$SERVER_NAME" \
        -keyout tls/server.key -out tls/server.crt 2>/dev/null
    chmod 644 tls/server.crt
fi
# The nginx master process reads the key as root at startup: owner-only is enough.
chmod 600 tls/server.key

say "building images (first run: several minutes)"
"${COMPOSE[@]}" build --pull

say "starting PostgreSQL and Redis"
"${COMPOSE[@]}" up -d --wait db redis

say "applying database migrations"
"${COMPOSE[@]}" run --rm api alembic upgrade head

say "agents' certificate authority"
"${COMPOSE[@]}" run --rm --user root --entrypoint sh api -c \
    'chown 10001:10001 /var/lib/carborewind/pki && chmod 700 /var/lib/carborewind/pki'
if "${COMPOSE[@]}" run --rm --entrypoint sh api -c 'test -f /var/lib/carborewind/pki/ca.key'; then
    echo "    CA already present: kept"
else
    "${COMPOSE[@]}" run --rm api carborewind-api pki-init
fi
# nginx needs to read ca.crt (public) through the read-only volume.
"${COMPOSE[@]}" run --rm --user root --entrypoint sh api -c 'chmod 755 /var/lib/carborewind/pki'

say "starting the whole stack"
"${COMPOSE[@]}" up -d --wait
# nginx keeps the certificate it loaded at startup: reload it so a new or renewed
# certificate (re-run with another --server-name or --tls-cert) is actually served.
"${COMPOSE[@]}" restart proxy

say "health check"
for _ in $(seq 1 30); do
    if curl -fsk --resolve "$SERVER_NAME:443:127.0.0.1" "https://$SERVER_NAME/readyz" >/dev/null; then
        ok=1; break
    fi
    sleep 2
done
[ "${ok:-0}" = 1 ] || die "the API does not answer on https://$SERVER_NAME/readyz — see: ${COMPOSE[*]} logs api proxy"

cat <<EOF

CarboRewind server is running: https://$SERVER_NAME

Next steps (see docs/install.md):
  1. First super-admin:
       cd $INSTALL_DIR/deploy && docker compose -f docker-compose.prod.yml run --rm api carborewind-api create-user admin
  2. Register the agent of your Carbonio server and get its one-time token:
       docker compose -f docker-compose.prod.yml run --rm api carborewind-api agent-create mx1 mail.example.org
  3. Copy to the Carbonio server the CA of this HTTPS certificate if it is self-signed:
       $INSTALL_DIR/deploy/tls/server.crt   ->   /etc/carborewind/api-ca.crt
EOF
